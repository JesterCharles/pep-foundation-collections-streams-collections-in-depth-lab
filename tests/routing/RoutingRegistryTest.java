package routing;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.ListIterator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.Set;
import java.util.Spliterator;
import java.util.function.Consumer;
import java.util.function.IntFunction;
import org.junit.jupiter.api.Test;

/**
 * Public tests for the order-routing registry. Every failure message starts with its task number.
 * Do not edit this file.
 */
class RoutingRegistryTest {

    private static Order order(String channel, int number, String sku, int quantity, String station) {
        return new Order(channel, number, sku, quantity, station);
    }

    /** Five arrivals over three stations; web-1001 and phone-1001 share a number but not a channel. */
    private static RoutingRegistry floor() {
        RoutingRegistry registry = new RoutingRegistry();
        for (Order o : List.of(
                order("web", 1001, "mug", 2, "B2"),
                order("phone", 1001, "lamp", 1, "A1"),
                order("web", 1002, "kettle", 1, "B2"),
                order("web", 1003, "mug", 4, "C3"),
                order("phone", 1002, "rug", 1, "A1"))) {
            registry.register(o);
        }
        return registry;
    }

    private static List<String> keys(List<Order> orders) {
        List<String> keys = new ArrayList<>();
        for (Order o : orders) {
            keys.add(o.key().toString());
        }
        return keys;
    }

    @Test
    void task1EqualKeysFindTheOrder() {
        OrderKey first = new OrderKey("web", 1002);
        OrderKey second = new OrderKey("web", 1002);
        assertTrue(first.equals(second), "Task 1: equals itself is given and should already hold");
        assertTrue(first.hashCode() == second.hashCode(),
                "Task 1: two equal OrderKeys (web-1002 and web-1002) must have equal hash codes");
        assertEquals(1, new HashSet<>(List.of(first, second)).size(),
                "Task 1: a HashSet must treat two equal OrderKeys as one element");
        RoutingRegistry registry = floor();
        Order kettle = registry.find("web", 1002);
        assertTrue(kettle != null && kettle.sku().equals("kettle"),
                "Task 1: find(\"web\", 1002) must return the kettle order, but returned " + kettle);
        assertNull(registry.find("phone", 1003), "Task 1: find(\"phone\", 1003) must return null: there is no such order");
        Order replaced = registry.register(order("web", 1002, "kettle", 2, "B2"));
        assertTrue(replaced != null && replaced.quantity() == 1,
                "Task 1: registering web-1002 again must replace the stored order and return the old one, but returned " + replaced);
        assertEquals(5, registry.orders().size(), "Task 1: replacing web-1002 must keep 5 orders, not add a sixth");
    }

    @Test
    void task2DropDiscontinuedRemovesSafely() {
        RoutingRegistry registry = floor();
        int[] removed = new int[1];
        assertDoesNotThrow(() -> removed[0] = registry.dropDiscontinued(Set.of("mug")),
                "Task 2: dropDiscontinued(mug) must not throw; remove through removeIf or an Iterator, not inside a for-each loop");
        assertEquals(2, removed[0], "Task 2: dropDiscontinued(mug) must report the 2 mug orders it removed");
        assertEquals(List.of("phone-1001", "web-1002", "phone-1002"), keys(registry.orders()),
                "Task 2: after dropping mug, the remaining orders must keep their arrival order");
        assertEquals(0, registry.dropDiscontinued(Set.of("teapot")), "Task 2: dropping an sku nobody ordered must remove 0");
    }

    @Test
    void task3QueueAndDispatchFirstInFirstOut() {
        RoutingRegistry registry = new RoutingRegistry();
        Order a = order("web", 1, "mug", 1, "B2");
        Order b = order("web", 2, "lamp", 1, "B2");
        Order c = order("web", 3, "rug", 1, "A1");
        registry.queue(a);
        registry.queue(b);
        registry.queue(c);
        assertEquals(List.of("web-1", "web-2"), keys(registry.waiting("B2")),
                "Task 3: queue must add orders to the back of their own station's queue");
        assertSame(a, registry.dispatchNext("B2"), "Task 3: dispatchNext(B2) must return the oldest B2 order, web-1, first");
        assertSame(b, registry.dispatchNext("B2"), "Task 3: the second dispatchNext(B2) must return web-2");
        Order[] empty = new Order[1];
        assertDoesNotThrow(() -> empty[0] = registry.dispatchNext("B2"),
                "Task 3: dispatchNext on an empty queue must return null, not throw; use poll, not remove or pop");
        assertNull(empty[0], "Task 3: dispatchNext(B2) must return null once B2 has nothing waiting");
        assertDoesNotThrow(() -> empty[0] = registry.dispatchNext("Z9"),
                "Task 3: dispatchNext on a station that never had a queue must return null, not throw");
        assertNull(empty[0], "Task 3: dispatchNext(Z9) must return null for an unknown station");
        assertEquals(List.of("web-3"), keys(registry.waiting("A1")), "Task 3: dispatching from B2 must leave A1's queue alone");
    }

    @Test
    void task4UndoLastDispatchLastInFirstOut() {
        RoutingRegistry registry = new RoutingRegistry();
        Order a = order("web", 1, "mug", 1, "B2");
        Order b = order("web", 2, "lamp", 1, "B2");
        Order c = order("web", 3, "rug", 1, "A1");
        for (Order o : List.of(a, b, c)) {
            registry.queue(o);
        }
        Order[] undone = new Order[1];
        assertDoesNotThrow(() -> undone[0] = registry.undoLastDispatch(),
                "Task 4: undoLastDispatch with nothing dispatched must return null, not throw");
        assertNull(undone[0], "Task 4: undoLastDispatch must return null when nothing has been dispatched");
        registry.dispatchNext("B2");
        registry.dispatchNext("A1");
        assertSame(c, registry.undoLastDispatch(), "Task 4: the first undo must return the newest dispatch, web-3 (needs Task 3 too)");
        assertEquals(List.of("web-3"), keys(registry.waiting("A1")), "Task 4: the undone web-3 must be back in A1's queue (needs Task 3 too)");
        assertSame(a, registry.undoLastDispatch(), "Task 4: the second undo must return the older dispatch, web-1 (needs Task 3 too)");
        assertEquals(List.of("web-1", "web-2"), keys(registry.waiting("B2")),
                "Task 4: the undone web-1 must be back at the head of B2's queue, ahead of web-2 (needs Task 3 too)");
        assertSame(a, registry.dispatchNext("B2"), "Task 4: after the undo, B2 must dispatch web-1 next again (needs Task 3 too)");
    }

    /**
     * A list that counts how often its contents are read: each call of iterator, listIterator,
     * spliterator (which stream uses), forEach, toArray, subList, contains, indexOf, lastIndexOf or
     * get counts as one read. It cannot see what happens to a copy made with one read.
     */
    private static final class CountingList extends ArrayList<String> {
        int reads;

        CountingList(List<String> items) {
            super(items);
        }

        @Override
        public Iterator<String> iterator() {
            reads++;
            return super.iterator();
        }

        @Override
        public Spliterator<String> spliterator() {
            reads++;
            return super.spliterator();
        }

        @Override
        public ListIterator<String> listIterator() {
            reads++;
            return super.listIterator();
        }

        @Override
        public ListIterator<String> listIterator(int index) {
            reads++;
            return super.listIterator(index);
        }

        @Override
        public void forEach(Consumer<? super String> action) {
            reads++;
            super.forEach(action);
        }

        @Override
        public Object[] toArray() {
            reads++;
            return super.toArray();
        }

        @Override
        public <T> T[] toArray(T[] a) {
            reads++;
            return super.toArray(a);
        }

        @Override
        public <T> T[] toArray(IntFunction<T[]> generator) {
            reads++;
            return super.toArray(generator);
        }

        @Override
        public List<String> subList(int fromIndex, int toIndex) {
            reads++;
            return super.subList(fromIndex, toIndex);
        }

        @Override
        public int lastIndexOf(Object o) {
            reads++;
            return super.lastIndexOf(o);
        }

        @Override
        public boolean contains(Object o) {
            reads++;
            return super.indexOf(o) >= 0;
        }

        @Override
        public int indexOf(Object o) {
            reads++;
            return super.indexOf(o);
        }

        @Override
        public String get(int index) {
            reads++;
            return super.get(index);
        }
    }

    @Test
    void task5HeldOrdersReadTheHeldListOnce() {
        RoutingRegistry registry = floor();
        CountingList held = new CountingList(List.of("lamp", "mug", "teapot"));
        assertEquals(List.of("web-1001", "phone-1001", "web-1003"), keys(registry.heldOrders(held)),
                "Task 5: heldOrders(lamp, mug, teapot) must return the held orders in arrival order");
        assertTrue(held.reads <= 1, "Task 5: heldOrders read the held-sku list " + held.reads
                + " times for 5 orders; read it once into a hash-based set, then look each sku up in that set");
        assertEquals(List.of(), registry.heldOrders(new CountingList(List.of())), "Task 5: with nothing on hold, no order is held");
    }

    @Test
    void task6UnitsByStationSortedByStation() {
        RoutingRegistry registry = new RoutingRegistry();
        String[] stations = {"D4", "B12", "A7", "C3", "B2", "A7", "D4"};
        int[] quantities = {1, 2, 3, 4, 5, 6, 7};
        for (int i = 0; i < stations.length; i++) {
            registry.register(order("web", i + 1, "mug", quantities[i], stations[i]));
        }
        Map<String, Integer> units = registry.unitsByStation();
        assertEquals(new TreeMap<>(Map.of("A7", 9, "B12", 2, "B2", 5, "C3", 4, "D4", 8)), new TreeMap<>(units),
                "Task 6: unitsByStation must total each station's units");
        assertEquals(List.of("A7", "B12", "B2", "C3", "D4"), new ArrayList<>(units.keySet()),
                "Task 6: unitsByStation must list stations in sorted (String) order, A7 before B12 before B2");
    }
}
